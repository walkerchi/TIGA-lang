def _operation_section(
    operation: str, record: dict, root: Path, lang: str,
    panel_baselines: dict[tuple[str, str], str],
) -> str:
    labels = LABELS[lang]
    title = ("邻居加权求和" if lang == "zh" else "Weighted neighbor sum") if operation == "weighted_aggregation" else operation
    lines = [
        f"### {title} {{ #matrix-{operation} }}",
        "",
        BLURBS[lang].get(operation, record.get("note", "")),
        "",
    ]
    summary = _weighted_summary(record, root, lang) if operation == "weighted_aggregation" else []
    intro_length = len(lines)
    gate_rows: list[str] = []
    fallback_rows: list[str] = []
    for case in record.get("cases", []):
        payload = _case_payload(operation, case, record, root)
        if payload is None:
            continue
        gates = payload.get("sota_gates") or []
        if gates:
            gate_rows.extend(_gate_rows(case, gates, labels))
        else:
            fallback_rows.extend(
                _provider_rows(
                    case, payload.get("results", []), labels,
                    declared_baseline=panel_baselines.get(
                        (operation, case))))
    if gate_rows:
        lines.append(
            f"| {labels['case']} | {labels['bucket']} "
            f"| {labels['candidate']} | {labels['baseline']} "
            f"| {labels['speedup']} | {labels['ci']} | {labels['gate']} |")
        lines.append("|---|---|---|---|---|---|---|")
        lines.extend(gate_rows)
        lines.append("")
    if fallback_rows:
        if gate_rows:
            lines.append(labels["fallback_note"])
            lines.append("")
        lines.append(
            f"| {labels['case']} | {labels['bucket']} | {labels['provider']} "
            f"| {labels['median']} | {labels['peer']} | {labels['vs_peer']} |")
        lines.append("|---|---|---|---|---|---|")
        lines.extend(fallback_rows)
        lines.append("")
    if summary:
        detail_title = "全部测量与实现细节" if lang == "zh" else "All measurements and implementation details"
        detail = ["    " + line if line else "" for line in lines[intro_length:]]
        lines = lines[:2] + summary + [f'??? info "{detail_title}"', ""] + detail
    return "\n".join(lines)


def build_matrix(manifest: dict, root: Path, lang: str) -> str:
    """Return the full-matrix include document for *lang*."""
    # Baselines predeclared by showcase/report panels win over the generic
    # best-non-Tiga peer in the provider fallback tables.
    panel_baselines = {
        (panel["operation"], panel["case"]): panel["baseline"]
        for key in ("showcase_panels", "report_panels")
        for panel in manifest.get(key, [])
        if panel.get("baseline")
    }
    sections = [HEADER, ""]
    for operation, record in manifest["operations"].items():
        sections.append(
            _operation_section(
                operation, record, root, lang, panel_baselines))
    return "\n".join(sections).rstrip() + "\n"


def main(
    manifest_path: Path = MANIFEST,
    root: Path = ROOFLINE_ROOT,
    out_dir: Path = INCLUDES,
) -> tuple[Path, Path]:
    manifest = json.loads(Path(manifest_path).read_text())
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    outputs = (
        out_dir / "full-matrix.md",
        out_dir / "full-matrix.zh.md",
    )
    for path, lang in zip(outputs, ("en", "zh")):
        path.write_text(build_matrix(manifest, Path(root), lang),
                        encoding="utf-8")
    for path in outputs:
        print(f"wrote {path}")
    return outputs


if __name__ == "__main__":
    main()
