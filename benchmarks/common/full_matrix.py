_CACHE_RANK = {"hot": 0, "consumer-only": 1, "cold": 2}


def _fmt_ms(value: float | None) -> str:
    return "—" if value is None else f"{value:.3f}"


def _fmt_speedup(value: float | None) -> str:
    return "—" if value is None else f"{value:.2f}×"


def _fmt_ci(low: float | None, high: float | None) -> str:
    if low is None or high is None:
        return "—"
    return f"[{low:.2f}, {high:.2f}]"


def _gate_bucket(gate: dict, *, with_nodes: bool) -> str:
    parts = [
        str(gate.get("topology") or "—"),
        str(gate.get("locality") or "—"),
        str(gate.get("cache") or "—"),
        f"F{gate.get('features')}",
    ]
    if with_nodes:
        parts.append(f"N{gate.get('nodes')}")
    return " · ".join(parts)


def _result_bucket(result: dict) -> str:
    parts = []
    if result.get("phase"):
        parts.append(str(result["phase"]))
    else:
        if result.get("topology"):
            parts.append(str(result["topology"]))
        if result.get("locality"):
            parts.append(str(result["locality"]))
    if result.get("cache"):
        parts.append(str(result["cache"]))
    if result.get("features") is not None:
        parts.append(f"F{result['features']}")
    return " · ".join(parts) or "—"


def _gate_sort_key(gate: dict) -> tuple:
    return (
        _CACHE_RANK.get(str(gate.get("cache")), 3),
        gate.get("features") or 0,
        str(gate.get("topology") or ""),
        str(gate.get("locality") or ""),
        -(gate.get("nodes") or 0),
    )


def _is_peer(provider: str) -> bool:
    """Return whether *provider* counts as a comparison peer.

    ``tiga.materialized_*`` providers are benchmark-only materialized
    pipeline baselines, so they rank as peers despite the prefix.
    """
    if provider.startswith("tiga.materialized"):
        return True
    return not provider.startswith("tiga")


def _case_payload(
    operation: str, case: str, record: dict, root: Path
) -> dict | None:
    artifact = record.get("artifact", "roofline.json")
    path = root / operation / case / artifact
    if not path.is_file():
        return None
    return json.loads(path.read_text())


def _gate_rows(case: str, gates: list[dict], labels: dict) -> list[str]:
    def _key(gate: dict) -> tuple:
        return (gate.get("topology"), gate.get("locality"),
                gate.get("cache"), gate.get("features"))

    seen = [_key(g) for g in gates]
    rows = []
    for gate in sorted(gates, key=_gate_sort_key):
        with_nodes = seen.count(_key(gate)) > 1
        rows.append(
            f"| <code>{case}</code> "
            f"| {_gate_bucket(gate, with_nodes=with_nodes)} "
            f"| `{gate['candidate']}` {_fmt_ms(gate.get('candidate_ms'))} "
            f"| `{gate['baseline']}` {_fmt_ms(gate.get('baseline_ms'))} "
            f"| {_fmt_speedup(gate.get('speedup_vs_sota'))} "
            f"| {_fmt_ci(gate.get('speedup_ci_low'), gate.get('speedup_ci_high'))} "
            f"| {labels['passed'] if gate.get('passed') else labels['failed']} |"
        )
    return rows


def _provider_rows(
    case: str, results: list[dict], labels: dict,
    declared_baseline: str | None = None,
) -> list[str]:
    buckets: dict[str, list[dict]] = {}
    for result in results:
        buckets.setdefault(_result_bucket(result), []).append(result)
    rows = []
    for bucket, items in buckets.items():
        peer = None
        if declared_baseline is not None:
            peer = next(
                (r for r in items if r.get("provider") == declared_baseline),
                None)
        if peer is None:
            peers = [r for r in items if _is_peer(str(r.get("provider", "")))]
            peer = min(peers, key=lambda r: r["milliseconds"]) if peers else None

        def _rank(result: dict) -> tuple:
            return (0 if not _is_peer(str(result["provider"])) else 1,
                    result["milliseconds"])

        for result in sorted(items, key=_rank):
            provider = str(result["provider"])
            if peer is None:
                speedup, peer_name = "—", "—"
            else:
                speedup = _fmt_speedup(
                    peer["milliseconds"] / result["milliseconds"])
                peer_name = f"`{peer['provider']}`"
            rows.append(
                f"| <code>{case}</code> | {bucket} | `{provider}` "
                f"| {_fmt_ms(result.get('milliseconds'))} "
                f"| {peer_name} | {speedup} |"
            )
    return rows


def _operation_section(
    operation: str, record: dict, root: Path, lang: str,
    panel_baselines: dict[tuple[str, str], str],
) -> str:
    labels = LABELS[lang]
    lines = [
        f"### {operation} {{ #matrix-{operation} }}",
        "",
        BLURBS[lang].get(operation, record.get("note", "")),
        "",
    ]
    gate_rows: list[str] = []
    fallback_rows: list[str] = []
    for case in record.get("cases", []):
        payload = _case_payload(operation, case, record, root)
        if payload is None:
            continue
        gates = payload.get("sota_gates") or []
        if gates:
            gate_rows.extend(_gate_rows(case, gates, labels))
        else:
            fallback_rows.extend(
                _provider_rows(
                    case, payload.get("results", []), labels,
                    declared_baseline=panel_baselines.get(
                        (operation, case))))
    if gate_rows:
        lines.append(
            f"| {labels['case']} | {labels['bucket']} "
            f"| {labels['candidate']} | {labels['baseline']} "
            f"| {labels['speedup']} | {labels['ci']} | {labels['gate']} |")
        lines.append("|---|---|---|---|---|---|---|")
        lines.extend(gate_rows)
        lines.append("")
    if fallback_rows:
        if gate_rows:
            lines.append(labels["fallback_note"])
            lines.append("")
        lines.append(
            f"| {labels['case']} | {labels['bucket']} | {labels['provider']} "
            f"| {labels['median']} | {labels['peer']} | {labels['vs_peer']} |")
        lines.append("|---|---|---|---|---|---|")
        lines.extend(fallback_rows)
        lines.append("")
    return "\n".join(lines)


def build_matrix(manifest: dict, root: Path, lang: str) -> str:
    """Return the full-matrix include document for *lang*."""
    # Baselines predeclared by showcase/report panels win over the generic
    # best-non-Tiga peer in the provider fallback tables.
    panel_baselines = {
        (panel["operation"], panel["case"]): panel["baseline"]
        for key in ("showcase_panels", "report_panels")
        for panel in manifest.get(key, [])
        if panel.get("baseline")
    }
    sections = [HEADER, ""]
    for operation, record in manifest["operations"].items():
        sections.append(
            _operation_section(
                operation, record, root, lang, panel_baselines))
    return "\n".join(sections).rstrip() + "\n"


def main(
    manifest_path: Path = MANIFEST,
    root: Path = ROOFLINE_ROOT,
    out_dir: Path = INCLUDES,
) -> tuple[Path, Path]:
    manifest = json.loads(Path(manifest_path).read_text())
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    outputs = (
        out_dir / "full-matrix.md",
        out_dir / "full-matrix.zh.md",
    )
    for path, lang in zip(outputs, ("en", "zh")):
        path.write_text(build_matrix(manifest, Path(root), lang),
                        encoding="utf-8")
    for path in outputs:
        print(f"wrote {path}")
    return outputs


if __name__ == "__main__":
    main()
